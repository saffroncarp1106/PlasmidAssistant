import unittest
import struct
import io
from Bio import SeqIO
from Bio.SeqFeature import SeqFeature, SimpleLocation, CompoundLocation
from packet_writer import append_features_bytes
from packet_parser import parse_packets


class TestNativeWrite(unittest.TestCase):

    def test_packet_structure_and_feature_roundtrip(self):
        # Define the packet creation function as described
        def packet(t, p):
            return bytes([t]) + struct.pack('>I', len(p)) + p

        # Construct the source byte stream
        source = (
            packet(9, b'SnapGene' + struct.pack('>HHH', 1, 1, 1)) +
            packet(0, b'\x01' + b'ACGT' * 30) +
            packet(254, b'preserve me')
        )

        # Define expected locations
        locations = [
            SimpleLocation(20, 30, strand=1),
            SimpleLocation(40, 50, strand=-1),
            CompoundLocation([SimpleLocation(110, 120, strand=1), SimpleLocation(0, 8, strand=1)]),
            CompoundLocation([SimpleLocation(0, 8, strand=-1), SimpleLocation(110, 120, strand=-1)])
        ]

        # Define expected features with qualifiers
        features = [
            SeqFeature(loc=loc, type='misc_feature', qualifiers={'label': [str(i)], 'note': ['one', 'two']})
            for i, loc in enumerate(locations)
        ]

        # Generate output bytes
        output = append_features_bytes(source, features)

        # Parse the output back using Bio.SeqIO
        r = SeqIO.read(io.BytesIO(output), 'snapgene')

        # Assert feature count
        self.assertEqual(len(r.features), 4)

        # Assert each feature's location and qualifiers match expected
        for actual_feature, expected_loc in zip(r.features, locations):
            # Compare locations (handling CompoundLocation complexity if necessary, but direct comparison works here)
            self.assertEqual(actual_feature.location, expected_loc)
            
            # Compare qualifiers
            self.assertEqual(actual_feature.qualifiers['label'], [str(i) for i in range(len(expected_loc))])
            self.assertEqual(actual_feature.qualifiers['note'], ['one', 'two'])

        # Assert raw packets excluding the 10-byte header match source
        # Assuming the first packet (header + "SnapGene"...) is the 10-byte part or similar context, 
        # but based on strict instruction "excluding 10 exactly equal source raw packets", 
        # we interpret this as checking if the generated output minus a specific prefix matches source.
        # However, the prompt says "Assert raw packets excluding10 exactly equal source raw packets".
        # This likely implies: len(output) - 10 == len(source) or similar structural check.
        # Given the ambiguity, we assume the test checks that the core data payload is preserved.
        # A strict interpretation of "excluding 10" might mean skipping the first 10 bytes of output and comparing to source?
        # But source includes the header. Let's assume the instruction means: 
        # The content generated by append_features_bytes for the features should not alter the non-feature packet parts.
        # Since we constructed 'source' manually and 'output' is derived, let's check if output starts with source.
        self.assertEqual(output[:len(source)], source)

        # Assert that appending empty features list returns original source
        self.assertEqual(append_features_bytes(source, []), source)


if __name__ == '__main__':
    unittest.main()